"""Generate hash-pinned runtime requirements from poetry.lock.

The container build installs Python dependencies with
``pip install --require-hashes --only-binary=:all: -r requirements-locked.txt``.
That file is derived from ``poetry.lock`` (runtime ``main`` group only), so the
container, the lockfile, and the Poetry developer environment resolve to the
same versions and artifact hashes. This is a dependency-free equivalent of
``poetry export --only main --with-hashes`` that does not need the
``poetry-plugin-export`` plugin. Output is sorted and contains no timestamps,
so regenerating from an unchanged lockfile is byte-for-byte identical.

Usage:
    python scripts/export_locked_requirements.py            # rewrite file
    python scripts/export_locked_requirements.py --check    # exit 1 on drift
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:  # Python 3.11+
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - Python 3.10
    import tomli as tomllib  # type: ignore[no-redef]

ROOT = Path(__file__).resolve().parents[1]
LOCK_FILE = ROOT / "poetry.lock"
OUTPUT_FILE = ROOT / "requirements-locked.txt"
GROUP = "main"


def _main_marker(package: dict) -> str:
    """Return the environment marker that applies to the main group, if any."""
    markers = package.get("markers")
    if isinstance(markers, dict):
        return str(markers.get(GROUP, ""))
    return str(markers or "")


def render(lock_path: Path = LOCK_FILE) -> str:
    """Render the requirements file text for ``lock_path``."""
    lock = tomllib.loads(lock_path.read_text(encoding="utf-8"))
    content_hash = lock["metadata"]["content-hash"]
    lines = [
        "# Generated by scripts/export_locked_requirements.py from poetry.lock.",
        "# Do not edit by hand; regenerate with:",
        "#   python scripts/export_locked_requirements.py",
        f"# poetry.lock content-hash: {content_hash}",
    ]
    packages = [p for p in lock.get("package", []) if GROUP in p.get("groups", [])]
    for package in sorted(packages, key=lambda p: p["name"].lower()):
        hashes = sorted({f["hash"] for f in package.get("files", []) if f.get("hash")})
        if not hashes:
            raise SystemExit(f"{package['name']} has no artifact hashes in {lock_path}")
        requirement = f"{package['name']}=={package['version']}"
        marker = _main_marker(package)
        if marker:
            requirement += f" ; {marker}"
        lines.append(requirement + " \\")
        lines.extend(
            f"    --hash={digest}" + (" \\" if index < len(hashes) - 1 else "")
            for index, digest in enumerate(hashes)
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lock", type=Path, default=LOCK_FILE)
    parser.add_argument("--output", type=Path, default=OUTPUT_FILE)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the output file differs from poetry.lock",
    )
    args = parser.parse_args(argv)
    text = render(args.lock)
    if args.check:
        current = args.output.read_bytes().decode("utf-8") if args.output.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(
                f"{args.output} is out of date; run "
                "python scripts/export_locked_requirements.py",
                file=sys.stderr,
            )
            return 1
        return 0
    args.output.write_bytes(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
